const crypto = require("node:crypto");
const fs = require("node:fs");
const fsp = require("node:fs/promises");
const path = require("node:path");
const OSS = require("ali-oss");

const PROJECT_ROOT = process.cwd();
const DEFAULT_SOURCE_ROOT = "D:\\aiproject\\AI全域运营\\AI全域智能体\\a 夏日生活小红书封面合集";
const STORAGE_PREFIX = "reference-templates/xiaohongshu/original";
const GENERATED_OUTPUT_PATH = path.join(
  PROJECT_ROOT,
  "apps",
  "server",
  "src",
  "modules",
  "works",
  "xhs-original-reference-templates.generated.ts",
);
const LOCAL_OSS_ROOT = path.join(PROJECT_ROOT, ".runtime", "local-oss");

async function main() {
  loadEnvFile(path.join(PROJECT_ROOT, ".env"));
  loadEnvFile(path.join(PROJECT_ROOT, ".env.local"));

  const sourceRoot = path.resolve(process.argv[2] || DEFAULT_SOURCE_ROOT);
  const imageFiles = await collectImageFiles(sourceRoot);
  if (!imageFiles.length) {
    throw new Error(`未在目录中找到图片文件：${sourceRoot}`);
  }

  const ossConfig = readOssConfig();
  const uploader = ossConfig ? createOssUploader(ossConfig) : createLocalUploader();
  const categoryMap = new Map();
  let itemOrder = 0;

  const items = [];
  for (const filePath of imageFiles) {
    const relativePath = normalizePath(path.relative(sourceRoot, filePath));
    const relativeDir = normalizePath(path.dirname(relativePath));
    const categoryKey = relativeDir === "." ? "" : relativeDir;
    const categoryLabel = buildCategoryLabel(relativeDir);
    let category = categoryMap.get(categoryKey);
    if (!category) {
      category = {
        id: `cat_${createHash(categoryKey || "root").slice(0, 10)}`,
        label: categoryLabel,
        sourcePath: relativeDir === "." ? "" : relativeDir,
        count: 0,
      };
      categoryMap.set(categoryKey, category);
    }

    const extension = path.extname(filePath).toLowerCase() || ".jpg";
    itemOrder += 1;
    category.count += 1;
    const itemId = `tpl_${createHash(relativePath).slice(0, 12)}`;
    const itemLabel = `${category.label} ${String(category.count).padStart(2, "0")}`;
    const storageKey = `${STORAGE_PREFIX}/${category.id}/${itemId}${extension}`;
    const buffer = await fsp.readFile(filePath);
    const contentType = getContentTypeByExtension(extension);
    await uploader.putObject(storageKey, buffer, contentType);

    items.push({
      id: itemId,
      title: itemLabel,
      order: itemOrder,
      categoryId: category.id,
      categoryLabel: category.label,
      fileName: `${itemId}${extension}`,
      sourcePath: relativePath,
      contentType,
      storageKey,
    });
  }

  const categories = Array.from(categoryMap.values()).sort((left, right) =>
    left.label.localeCompare(right.label, "zh-CN"),
  );

  const generatedAt = new Date().toISOString();
  const library = {
    generatedAt,
    sourceRoot,
    storageMode: uploader.mode,
    storagePrefix: STORAGE_PREFIX,
    categories,
    items,
  };

  const fileContent = [
    "/* eslint-disable */",
    "// Auto-generated by scripts/import-xhs-original-reference-templates.cjs",
    `export const XHS_ORIGINAL_REFERENCE_TEMPLATE_LIBRARY = ${JSON.stringify(library, null, 2)};`,
    "",
  ].join("\n");
  await fsp.mkdir(path.dirname(GENERATED_OUTPUT_PATH), { recursive: true });
  await fsp.writeFile(GENERATED_OUTPUT_PATH, fileContent, "utf8");

  console.log(
    JSON.stringify(
      {
        generatedAt,
        sourceRoot,
        storageMode: uploader.mode,
        categoryCount: categories.length,
        itemCount: items.length,
        outputFile: GENERATED_OUTPUT_PATH,
      },
      null,
      2,
    ),
  );
}

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const text = fs.readFileSync(filePath, "utf8");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex <= 0) {
      continue;
    }
    const key = trimmed.slice(0, separatorIndex).trim();
    let value = trimmed.slice(separatorIndex + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!process.env[key]) {
      process.env[key] = value;
    }
  }
}

function readOssConfig() {
  const accessKeyId = String(process.env.OSS_ACCESS_KEY_ID || "").trim();
  const accessKeySecret = String(process.env.OSS_ACCESS_KEY_SECRET || "").trim();
  const bucket = String(process.env.OSS_BUCKET || "").trim();
  const region = String(process.env.OSS_REGION || "").trim();
  if (!accessKeyId || !accessKeySecret || !bucket || !region) {
    return null;
  }
  return {
    accessKeyId,
    accessKeySecret,
    bucket,
    region,
    internal: readBooleanEnv("OSS_INTERNAL", false),
  };
}

function createOssUploader(config) {
  const client = new OSS({
    region: config.region,
    bucket: config.bucket,
    accessKeyId: config.accessKeyId,
    accessKeySecret: config.accessKeySecret,
    internal: Boolean(config.internal),
    secure: true,
  });
  return {
    mode: "oss",
    async putObject(storageKey, buffer, contentType) {
      await client.put(storageKey, buffer, {
        headers: {
          "Content-Type": contentType,
          "Cache-Control": "public, max-age=31536000",
        },
      });
    },
  };
}

function createLocalUploader() {
  return {
    mode: "local-fallback",
    async putObject(storageKey, buffer, contentType) {
      const normalizedKey = normalizePath(storageKey);
      const filePath = path.join(LOCAL_OSS_ROOT, normalizedKey);
      const metaPath = `${filePath}.meta.json`;
      await fsp.mkdir(path.dirname(filePath), { recursive: true });
      await fsp.writeFile(filePath, buffer);
      await fsp.writeFile(metaPath, JSON.stringify({ contentType }, null, 2), "utf8");
    },
  };
}

async function collectImageFiles(sourceRoot) {
  const entries = await fsp.readdir(sourceRoot, { withFileTypes: true });
  const result = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name, "zh-CN"))) {
    const targetPath = path.join(sourceRoot, entry.name);
    if (entry.isDirectory()) {
      result.push(...(await collectImageFiles(targetPath)));
      continue;
    }
    if (!entry.isFile()) {
      continue;
    }
    if (/\.(jpg|jpeg|png|webp)$/i.test(entry.name)) {
      result.push(targetPath);
    }
  }
  return result;
}

function buildCategoryLabel(relativeDir) {
  if (!relativeDir || relativeDir === ".") {
    return "默认分类";
  }
  return relativeDir
    .split("/")
    .filter(Boolean)
    .map((segment) => segment.replace(/^[a-z]\s+/i, ""))
    .join(" / ");
}

function readBooleanEnv(key, fallback) {
  const raw = String(process.env[key] || "").trim().toLowerCase();
  if (!raw) {
    return fallback;
  }
  if (["1", "true", "yes", "on"].includes(raw)) {
    return true;
  }
  if (["0", "false", "no", "off"].includes(raw)) {
    return false;
  }
  return fallback;
}

function getContentTypeByExtension(extension) {
  switch (extension.toLowerCase()) {
    case ".png":
      return "image/png";
    case ".webp":
      return "image/webp";
    case ".jpg":
    case ".jpeg":
    default:
      return "image/jpeg";
  }
}

function createHash(value) {
  return crypto.createHash("sha1").update(String(value)).digest("hex");
}

function normalizePath(value) {
  return String(value || "").replace(/\\/g, "/").replace(/^\/+/, "");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
